def arbora_entry(n: dict[str, str], profile: dict[str, str]) -> str:
    entry = {
        "connector": n["fleet"],
        "server": n["fleet"],
        "transport": "streamable-http",
        "url": f"http://{n['fleet']}.{profile['namespace']}.svc/mcp",
        "namespaces": "lazy",
        "coverage_gate": "ARBORA-FLEET-R060",
    }
    return "# arbora fleet onboarding entry for one connector.\n" + json.dumps(entry, indent=2) + "\n"


def bundle(n: dict[str, str], profile: dict[str, str], upstream_url: str | None) -> dict[str, str]:
    """Return every deployment file as path relative to the output dir -> text."""
    fields = {**n, **profile}
    if upstream_url:
        fields["upstream_env"] = (
            f"        - name: {n['upper']}_UPSTREAM_URL\n          value: {upstream_url}\n"
        )
        fields["store_extra"] = ", and optionally `" + n["upper"] + "_ALLOWED_SCOPES`"
    else:
        fields["upstream_env"] = ""
        fields["store_extra"] = f" and `{n['upper']}_BASE_URL`"
    fleet = n["fleet"]
    files = {
        f"images/{fleet}/Dockerfile": IMAGE_DOCKERFILE,
        f"images/{fleet}/.gitlab-ci.yml": IMAGE_CI,
        f"images/{fleet}/README.md": IMAGE_README,
        f"services/{fleet}/k8s/manifests.yaml": MANIFESTS,
        f"services/{fleet}/README.md": SERVICES_README,
        f"onboarding/{fleet}/workspace-entry.yml": WORKSPACE_ENTRY,
    }
    out = {path: text.format(**fields) for path, text in files.items()}
    out[f"onboarding/{fleet}/arbora-connector.yml"] = arbora_entry(n, profile)
    return out
