"""The deployment bundle of a scaffolded connector (US-MCP-BUILDER-R013).

Beside the repository tree, `scaffold_connector.py` writes:

- `images/<fleet>/`: the private-registry build of the published release;
- `services/<fleet>/k8s/manifests.yaml`: Deployment, Service, Ingress and an
  ExternalSecret that holds a store key only, never a value;
- `onboarding/<fleet>/workspace-entry.yml`: the workspace manifest snippet;
- `onboarding/<fleet>/arbora-connector.yml`: the arbora fleet onboarding entry.

Site values (registry, domain, namespace, secret store, CI include) come from a
deploy profile, a small YAML file kept with the private deployment repos. The
neutral default profile names no real host, so this public scaffold carries
none. The image always installs the published release: no source mount.
"""

from __future__ import annotations

import json
from pathlib import Path

DEFAULT_PROFILE = {
    "registry": "registry.example.invalid",
    "domain": "example.invalid",
    "namespace": "apps",
    "secret_store": "openbao",
    "ci_include_project": "pipelines/ci",
    "ci_include_file": "docker_registry_build_refresh.yml",
    "repo_origin": "https://github.com/Knuckles-Team",
    "base_image": "python:3.14-slim",
}


def load_profile(path: Path | None) -> dict[str, str]:
    profile = dict(DEFAULT_PROFILE)
    if path is not None:
        import yaml

        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        unknown = sorted(set(data) - set(DEFAULT_PROFILE))
        if unknown:
            raise SystemExit(f"unknown deploy profile keys: {', '.join(unknown)}")
        profile.update({key: str(value) for key, value in data.items()})
    return profile


